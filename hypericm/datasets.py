@dataclass(frozen=True)
class DatasetSpec:
    name: str
    bands: int
    wavelength_start: float
    wavelength_end: float
    base_gsd: float
    few_shot_points: tuple[tuple[int, int, int], ...]

    @property
    def wavelengths(self) -> list[float]:
        exact = _EXACT_WAVELENGTHS.get(self.name)
        if exact is not None:
            if len(exact) != self.bands:
                raise ValueError(
                    f"{self.name} defines {len(exact)} wavelengths but expects {self.bands} bands."
                )
            return list(exact)
        if self.bands == 1:
            return [self.wavelength_start]
        step = (self.wavelength_end - self.wavelength_start) / (self.bands - 1)
        return [self.wavelength_start + step * index for index in range(self.bands)]


